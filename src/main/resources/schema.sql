-- H2 本地文件数据库初始化脚本。
-- F1：农机底账 + 作业单主链路（建档/状态流转/轨迹面积/红冲）。
-- 约定：历史数据不物理删除，停用/红冲只改状态；所有写请求凭请求号登记 t_request_record。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- 农机基础信息
CREATE TABLE IF NOT EXISTS t_machine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code VARCHAR(40) NOT NULL,
    machine_name VARCHAR(80) NOT NULL,
    machine_type VARCHAR(40),
    plate_no VARCHAR(40),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_machine_code UNIQUE (machine_code)
);

-- 作业单（track_area 为轨迹核算的权威面积，manual_area 仅人工上报参考）
CREATE TABLE IF NOT EXISTS t_work_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL,
    machine_id BIGINT NOT NULL,
    operation_type VARCHAR(40) NOT NULL,
    plot_name VARCHAR(80),
    track_area DECIMAL(12, 2),
    track_time TIMESTAMP,
    manual_area DECIMAL(12, 2),
    manual_reporter VARCHAR(64),
    manual_report_time TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    reversal_flag CHAR(1) NOT NULL DEFAULT '0',
    origin_order_id BIGINT,
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_work_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_work_order_machine ON t_work_order (machine_id);

-- 作业单状态流转日志
CREATE TABLE IF NOT EXISTS t_work_order_status_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    request_no VARCHAR(64),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_status_log_order ON t_work_order_status_log (order_id);

-- 请求号台账：新增/变更请求必须携带请求号，全局唯一，防重放
CREATE TABLE IF NOT EXISTS t_request_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no VARCHAR(64) NOT NULL,
    biz_type VARCHAR(32) NOT NULL,
    biz_key VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    CONSTRAINT uk_request_no UNIQUE (request_no)
);

-- F2：与卫星轨迹核算平台每日对账（定时勾稽 / 差异清单 / 核销 / 新旧引擎并跑）。

-- 卫星平台账单明细（对方账）：由导入接口按账期推送，同账期同单号只一条
CREATE TABLE IF NOT EXISTS t_sat_bill_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_date DATE NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    machine_code VARCHAR(40),
    track_area DECIMAL(12, 2) NOT NULL,
    source_batch VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_sat_bill_line UNIQUE (bill_date, order_no)
);
CREATE INDEX IF NOT EXISTS idx_sat_bill_line_date ON t_sat_bill_line (bill_date);

-- 勾稽批次：每次调度/手工触发一条；重跑不删历史，旧批次置 SUPERSEDED
CREATE TABLE IF NOT EXISTS t_recon_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_no VARCHAR(40) NOT NULL,
    biz_date DATE NOT NULL,
    engine VARCHAR(16) NOT NULL,
    trigger_type VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'SUCCESS',
    local_count INT NOT NULL DEFAULT 0,
    remote_count INT NOT NULL DEFAULT 0,
    matched_count INT NOT NULL DEFAULT 0,
    diff_count INT NOT NULL DEFAULT 0,
    total_diff_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    message VARCHAR(255),
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_recon_run_no UNIQUE (run_no)
);
CREATE INDEX IF NOT EXISTS idx_recon_run_date ON t_recon_run (biz_date);

-- 勾稽差异清单：只放差异（双边面积不符 / 单方缺账），双方明细快照随行保留
CREATE TABLE IF NOT EXISTS t_recon_diff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    biz_date DATE NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    diff_type VARCHAR(16) NOT NULL,
    local_order_id BIGINT,
    local_track_area DECIMAL(12, 2),
    remote_track_area DECIMAL(12, 2),
    diff_area DECIMAL(12, 2),
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    writeoff_id BIGINT,
    writeoff_time TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_recon_diff_run ON t_recon_diff (run_id);
CREATE INDEX IF NOT EXISTS idx_recon_diff_date_status ON t_recon_diff (biz_date, status);

-- 核销单：手工调整走核销，一笔差异只核销一次（uk_recon_writeoff_diff 兜底），核销后差异即时清零
CREATE TABLE IF NOT EXISTS t_recon_writeoff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    writeoff_no VARCHAR(40) NOT NULL,
    diff_id BIGINT NOT NULL,
    request_no VARCHAR(64) NOT NULL,
    biz_date DATE NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    adjust_area DECIMAL(12, 2) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_recon_writeoff_no UNIQUE (writeoff_no),
    CONSTRAINT uk_recon_writeoff_diff UNIQUE (diff_id)
);

-- 新旧引擎并跑对比：每次勾稽双引擎各跑一遍，汇总落此表；连续两天 identical=1 后切 active-engine
CREATE TABLE IF NOT EXISTS t_recon_compare (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_date DATE NOT NULL,
    run_id BIGINT NOT NULL,
    active_engine VARCHAR(16) NOT NULL,
    legacy_matched INT NOT NULL DEFAULT 0,
    legacy_diff_count INT NOT NULL DEFAULT 0,
    legacy_diff_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    tolerance_matched INT NOT NULL DEFAULT 0,
    tolerance_diff_count INT NOT NULL DEFAULT 0,
    tolerance_diff_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    identical CHAR(1) NOT NULL DEFAULT '0',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_recon_compare_date ON t_recon_compare (biz_date);

